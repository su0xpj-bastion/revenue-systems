"""npi: new product introduction toolkit.

  python -m npi validate SPEC
  python -m npi catalog SPEC --current CSV --out DIR
  python -m npi scenarios SPEC SCENARIOS
  python -m npi readiness SPEC TRACKER [--today YYYY-MM-DD] [--out FILE]
  python -m npi migrate SPEC SUBSCRIPTIONS [--as-of YYYY-MM-DD]
  python -m npi reconcile SPEC DATA_DIR [--out FILE]
  python -m npi draft BRIEF --out SPEC            (Claude)
  python -m npi propose-scenarios SPEC --out FILE (Claude)
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from dataclasses import asdict
from datetime import date
from decimal import Decimal
from pathlib import Path

import yaml

from . import catalog, migration, readiness, reconcile, scenarios
from .lint import blocking, lint
from .pricing import QuoteLine, invoice_schedule
from .spec import SpecError, load_spec, parse_spec


def cmd_validate(args) -> int:
    launch = load_spec(args.spec)
    findings = lint(launch)
    for f in findings:
        print(f)
    blocks = blocking(findings)
    print(f"\n{len(blocks)} blocking, {len(findings) - len(blocks)} warnings")
    return 1 if blocks else 0


def cmd_catalog(args) -> int:
    launch = load_spec(args.spec)
    paths = catalog.write_tables(catalog.build_catalog(launch), args.out)
    current = catalog.read_csv(args.current) if args.current else []
    changes = catalog.diff_catalog(launch, current)
    plan = [f"# Catalog change plan: {launch.code}", "", "| Action | SKU | Detail |", "|---|---|---|"]
    plan += [f"| {c.action} | {c.sku} | {c.detail} |" for c in changes]
    (args.out / "change_plan.md").write_text("\n".join(plan) + "\n", encoding="utf-8")
    for p in paths:
        print(f"wrote {p}")
    print(f"wrote {args.out / 'change_plan.md'}")
    return 0


def cmd_scenarios(args) -> int:
    launch = load_spec(args.spec)
    results = scenarios.run_all(launch, scenarios.load_scenarios(args.scenarios))
    for r in results:
        mark = "PASS" if r.passed else "FAIL"
        detail = r.error or f"total {r.total} · first invoice {r.first_invoice} · approver {r.approver}"
        print(f"{mark}  {r.scenario.name}: {detail}")
        for problem in r.problems:
            print(f"      ✗ {problem}")
    failed = sum(not r.passed for r in results)
    print(f"\n{len(results) - failed}/{len(results)} scenarios pass")
    return 1 if failed else 0


def cmd_readiness(args) -> int:
    launch = load_spec(args.spec)
    done, signoffs = readiness.load_tracker(args.tracker)
    today = date.fromisoformat(args.today) if args.today else date.today()
    text = readiness.report(launch, done, signoffs, today)
    if args.out:
        args.out.write_text(text, encoding="utf-8")
    print(text)
    go, _ = readiness.go_no_go(launch, done, signoffs, today)
    return 0 if go else 2


def cmd_migrate(args) -> int:
    launch = load_spec(args.spec)
    as_of = date.fromisoformat(args.as_of) if args.as_of else date.today()
    rows = migration.plan_migrations(launch, catalog.read_csv(args.subscriptions), as_of)
    writer = csv.writer(sys.stdout)
    writer.writerow(["account", "subscription_id", "sku", "replacement", "effective",
                     "old_monthly", "new_monthly", "uplift_pct", "amendment_net", "action", "flags"])
    for r in rows:
        writer.writerow([r.account, r.subscription_id, r.sku, r.replacement, r.effective,
                         r.old_monthly, r.new_monthly, r.uplift_pct,
                         "" if r.amendment_net is None else r.amendment_net, r.action, " | ".join(r.flags)])
    print(json.dumps(migration.summarize(rows)), file=sys.stderr)
    return 0


def cmd_reconcile(args) -> int:
    launch = load_spec(args.spec)
    results = reconcile.run_controls(launch, args.data_dir)
    text = reconcile.render(results)
    if args.out:
        args.out.write_text(text, encoding="utf-8")
    print(text)
    return 0 if all(r.passed for r in results) else 1


def _client():
    import anthropic
    return anthropic.Anthropic()


def cmd_draft(args) -> int:
    from .ai import draft_spec
    data = draft_spec(_client(), args.brief.read_text(encoding="utf-8"))
    header = ("# DRAFT generated by Claude from "
              f"{args.brief.name}. Validate, review and get sign-off before use.\n")
    args.out.write_text(header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"wrote {args.out}\n")
    try:
        launch = parse_spec(data)
    except SpecError as exc:
        print(f"draft does not parse: {exc}")
        return 1
    findings = lint(launch)
    for f in findings:
        print(f)
    return 1 if blocking(findings) else 0


def cmd_propose(args) -> int:
    from .ai import propose_scenarios
    launch = load_spec(args.spec)
    proposed = propose_scenarios(_client(), args.spec.read_text(encoding="utf-8"), args.count)
    out = []
    for s in proposed:
        entry = dict(s)
        try:
            lines = [QuoteLine(l["sku"], Decimal(str(l["quantity"])), Decimal(str(l["discount_pct"])))
                     for l in s["lines"]]
            usage = {k: [Decimal(str(u)) for u in v] for k, v in s["usage"].items()}
            invoices = invoice_schedule(launch, lines, date.fromisoformat(s["start"]), usage)
            entry["computed"] = {"total": float(sum(i.amount for i in invoices))}
        except ValueError as exc:
            entry["computed"] = {"error": str(exc)}
        out.append(entry)
    header = ("# PROPOSED by Claude. Inputs only; `computed` values come from the pricing engine.\n"
              "# Review each, then move agreed values into `expect` in the scenario suite.\n")
    args.out.write_text(header + yaml.safe_dump({"scenarios": out}, sort_keys=False), encoding="utf-8")
    print(f"wrote {len(out)} scenarios to {args.out}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(prog="npi", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("validate"); p.add_argument("spec", type=Path); p.set_defaults(func=cmd_validate)
    p = sub.add_parser("catalog"); p.add_argument("spec", type=Path)
    p.add_argument("--current", type=Path); p.add_argument("--out", type=Path, required=True)
    p.set_defaults(func=cmd_catalog)
    p = sub.add_parser("scenarios"); p.add_argument("spec", type=Path); p.add_argument("scenarios", type=Path)
    p.set_defaults(func=cmd_scenarios)
    p = sub.add_parser("readiness"); p.add_argument("spec", type=Path); p.add_argument("tracker", type=Path)
    p.add_argument("--today"); p.add_argument("--out", type=Path); p.set_defaults(func=cmd_readiness)
    p = sub.add_parser("migrate"); p.add_argument("spec", type=Path); p.add_argument("subscriptions", type=Path)
    p.add_argument("--as-of"); p.set_defaults(func=cmd_migrate)
    p = sub.add_parser("reconcile"); p.add_argument("spec", type=Path); p.add_argument("data_dir", type=Path)
    p.add_argument("--out", type=Path); p.set_defaults(func=cmd_reconcile)
    p = sub.add_parser("draft"); p.add_argument("brief", type=Path); p.add_argument("--out", type=Path, required=True)
    p.set_defaults(func=cmd_draft)
    p = sub.add_parser("propose-scenarios"); p.add_argument("spec", type=Path)
    p.add_argument("--out", type=Path, required=True); p.add_argument("--count", type=int, default=10)
    p.set_defaults(func=cmd_propose)

    args = parser.parse_args()
    try:
        return args.func(args)
    except SpecError as exc:
        print(f"spec error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
